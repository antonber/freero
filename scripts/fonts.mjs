#!/usr/bin/env node
// Vendors the board's typefaces (openly licensed only) into the repo, so the app never asks a font
// CDN at runtime: `node scripts/fonts.mjs` downloads each family's .woff2 files from Fontsource
// (pinned to the version below), writes the @font-face CSS next to them, and the family's licence.
//
//   apps/web/src/ui/fonts/       the four the app's own UI uses too (Inter, Source Serif 4,
//                                JetBrains Mono, Caveat): loaded with the design tokens
//   apps/web/src/engine/text/fonts/  the board's other families: their CSS rides in the board's
//                                chunk only
//
// @font-face rules cost nothing until text in that family (and that unicode-range) is drawn: the
// browser fetches a file the first time it is needed. Re-run after changing FAMILIES; commit the
// result. Fails on any licence other than OFL-1.1 / Apache-2.0.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const UI = path.join(ROOT, 'apps/web/src/ui/fonts');
const BOARD = path.join(ROOT, 'apps/web/src/engine/text/fonts');

/** Fontsource id → the CSS family name, weights, and where it goes. */
const FAMILIES = [
  { id: 'inter', weights: [400, 500, 600, 700], dir: UI },
  { id: 'source-serif-4', weights: [400, 600], dir: UI },
  { id: 'jetbrains-mono', weights: [400, 600], dir: UI },
  { id: 'caveat', weights: [500, 700], dir: UI },
  { id: 'atkinson-hyperlegible', weights: [400, 700], dir: BOARD },
  { id: 'nunito', weights: [400, 700], dir: BOARD },
  { id: 'montserrat', weights: [400, 700], dir: BOARD },
  { id: 'space-grotesk', weights: [400, 700], dir: BOARD },
  { id: 'oswald', weights: [400, 700], dir: BOARD },
  { id: 'lora', weights: [400, 700], dir: BOARD },
  { id: 'playfair-display', weights: [400, 700], dir: BOARD },
  { id: 'bitter', weights: [400, 700], dir: BOARD },
  { id: 'courier-prime', weights: [400, 700], dir: BOARD },
  { id: 'patrick-hand', weights: [400], dir: BOARD },
  { id: 'permanent-marker', weights: [400], dir: BOARD },
];
/** Scripts we ship (each its own file; the browser loads only those a text uses). */
const SUBSETS = ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext', 'greek', 'vietnamese'];
const LICENCES = new Set(['OFL-1.1', 'Apache-2.0']);

async function get(url, as = 'json') {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return as === 'json' ? res.json() : as === 'text' ? res.text() : Buffer.from(await res.arrayBuffer());
}

const css = new Map([[UI, []], [BOARD, []]]);
for (const dir of css.keys()) {
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(path.join(dir, 'files'), { recursive: true });
}

for (const f of FAMILIES) {
  const meta = await get(`https://api.fontsource.org/v1/fonts/${f.id}`);
  if (!LICENCES.has(meta.license)) throw new Error(`${f.id}: licence ${meta.license} is not allowed`);
  const licence = await get(`https://cdn.jsdelivr.net/npm/@fontsource/${f.id}@${meta.npmVersion}/LICENSE`, 'text');
  fs.writeFileSync(path.join(f.dir, 'files', `${f.id}.LICENSE.txt`), licence);
  const rules = css.get(f.dir);
  rules.push(`/* ${meta.family} (${meta.license}, Fontsource ${meta.npmVersion}): files/${f.id}.LICENSE.txt */`);
  for (const w of f.weights) {
    for (const subset of SUBSETS) {
      const url = meta.variants?.[w]?.normal?.[subset]?.url?.woff2;
      if (!url) continue;
      const file = `${f.id}-${subset}-${w}.woff2`;
      fs.writeFileSync(path.join(f.dir, 'files', file), await get(url, 'bin'));
      rules.push(
        `@font-face {\n  font-family: '${meta.family}';\n  font-style: normal;\n  font-display: swap;\n  font-weight: ${w};\n  src: url('./files/${file}') format('woff2');\n  unicode-range: ${meta.unicodeRange[subset]};\n}`,
      );
    }
  }
  console.log(`${meta.family}: ${f.weights.join(', ')}`);
}

const header = (what) =>
  `/* Generated by scripts/fonts.mjs: ${what}. Self-hosted, openly licensed; a file is fetched only when\n   text in that family and script is drawn. Don't edit by hand. */\n`;
fs.writeFileSync(path.join(UI, 'fonts.css'), header("the app's own typefaces") + css.get(UI).join('\n') + '\n');
fs.writeFileSync(path.join(BOARD, 'fonts.css'), header("the board's other typefaces") + css.get(BOARD).join('\n') + '\n');
