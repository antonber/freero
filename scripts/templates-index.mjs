#!/usr/bin/env node
// Regenerates the spec templates' catalog index (apps/web/src/features/templates/lib/specs/index.ts)
// from the spec files beside it: what the picker lists and searches before any spec file loads,
// and one lazy loader per file. Run after adding or editing a spec:
//
//   npm run templates:index
//
// The templates tests fail while the index is out of date.
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'apps/web/src/features/templates/lib/specs');
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts' && !f.endsWith('.test.ts'))
  .sort();

const entries = [];
for (const f of files) {
  const mod = await import(pathToFileURL(path.join(dir, f)).href);
  const file = f.replace(/\.ts$/, '');
  if (!Array.isArray(mod.default)) throw new Error(`${f}: the default export must be an array of template specs`);
  for (const s of mod.default) {
    entries.push({ id: s.id, name: s.name, description: s.description, categories: s.categories, keywords: s.keywords, archetype: s.archetype, file });
  }
}

const out = `// GENERATED by \`npm run templates:index\` from the spec files beside it. Don't edit by hand.
import type { SpecFiles } from '../spec/catalog';
import type { SpecIndexEntry } from '../spec/types';

export const SPEC_FILES: SpecFiles = {
${files.map((f) => `  '${f.replace(/\.ts$/, '')}': () => import('./${f.replace(/\.ts$/, '')}'),`).join('\n')}
};

export const SPEC_INDEX: SpecIndexEntry[] = [
${entries.map((e) => `  ${JSON.stringify(e)},`).join('\n')}
];
`;
writeFileSync(path.join(dir, 'index.ts'), out);
console.log(`templates:index: ${entries.length} spec templates in ${files.length} files`);
