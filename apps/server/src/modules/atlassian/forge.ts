// The Atlassian Forge app of THIS instance (#166, #167; docs/integrations/atlassian.md): the source
// of a Forge app the operator deploys with Atlassian's `forge` command — a Confluence macro and a
// Jira issue panel that show a Freero board live, through /atlassian/b/<id> (the public embed,
// framed by Atlassian's hosts only). Built from the instance's address and the operator's Forge app
// id, so every self-hosted Freero offers its own; nothing in it is secret.
//
// - Confluence: the "Freero board" macro (pick a board by its link in the macro's configuration),
//   and pasting a board link of this instance turns it into the macro (autoConvert). Page exports
//   (PDF, Word) get the board's link, with its picture for a board anyone with the link may view
//   (adfExport, through Freero's oEmbed).
// - Jira: the "Freero board" issue panel shows the board the issue was linked to by Freero's tracker
//   sync (the issue's remote link from Freero), or one the person picks for the issue (an issue
//   property).
//
// Atlassian's packages the app runs on (@forge/bridge, @forge/api, @forge/cli) are under the
// Atlassian Developer Terms: they are dependencies of the generated project only, installed by the
// operator, never of Freero.
import { zipSync } from 'fflate';
import { colorIcon } from '../../platform/brandIcons';

export const FORGE_PACKAGE_PATH = '/api/integrations/atlassian/forge-app';

/** The Forge app's source files (path → contents) for an instance at `origin`. */
export function forgeAppFiles(origin: string, appId: string): Record<string, string | Uint8Array> {
  const { host } = new URL(origin);
  const q = (s: string) => JSON.stringify(s);
  const manifest = `# Freero for Confluence and Jira — generated by ${host} (docs/integrations/atlassian.md).
# Deploy: npm install && npm run build && forge deploy -e production && forge install
app:
  id: ${appId}
  runtime:
    name: nodejs22.x
modules:
  macro:
    - key: freero-board
      resource: board
      title: Freero board
      description: A live Freero whiteboard. People see it as Freero shares it with them.
      icon: ${origin}/freero.svg
      layout: block
      viewportSize: large
      config:
        resource: board-config
        viewportSize: medium
        title: Choose a Freero board
      autoConvert:
        matchers:
          - pattern: ${origin}/board/*
          - pattern: ${origin}/embed/b/*
      adfExport:
        function: export-board
  jira:issuePanel:
    - key: freero-issue-board
      resource: board
      title: Freero board
      icon: ${origin}/freero.svg
      viewportSize: large
  function:
    - key: export-board
      handler: index.exportBoard
resources:
  - key: board
    path: static/board
  - key: board-config
    path: static/config
permissions:
  scopes:
    # Jira: the issue's remote links (Freero's tracker sync writes one per linked item) and the
    # board picked for an issue (an issue property).
    - read:jira-work
    - write:jira-work
  external:
    # Only Freero's board pages may be framed, nothing else.
    frames:
      - ${origin}/atlassian/b/
    # Atlassian lets frames open windows (Freero's sign-in window) only with this permission
    # (allow-popups, allow-popups-to-escape-sandbox): the app itself fetches nothing in the browser.
    fetch:
      client:
        - address: "*"
      # Page exports read the board's public preview (oEmbed) for its picture.
      backend:
        - ${origin}
`;

  const pkg = {
    name: `freero-atlassian-${host.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}`,
    version: '1.0.0',
    private: true,
    license: 'MIT',
    description: `Freero boards in Confluence pages and Jira issues, for ${host}.`,
    main: 'src/index.js',
    scripts: {
      build: 'esbuild static-src/board.js --bundle --minify --format=iife --outfile=static/board/board.js && esbuild static-src/config.js --bundle --minify --format=iife --outfile=static/config/config.js',
    },
    // Atlassian's packages (Atlassian Developer Terms) and esbuild (MIT), installed by whoever deploys.
    dependencies: { '@forge/api': '^6.0.0', '@forge/bridge': '^7.0.0' },
    devDependencies: { esbuild: '^0.25.0' },
  };

  const shared = `// Generated by ${host}. Which Freero board a link names, and how to show it.
export const FREERO = ${q(origin)};
const BOARD = /^\\/(?:board|embed\\/b|atlassian\\/b|teams\\/b)\\/([A-Za-z0-9_-]{1,64})\\/?$/;

/** { boardId, item } for a link to a board of this Freero (item: a frame or item to start at), else null. */
export function boardFromLink(link) {
  try {
    const u = new URL(String(link || '').trim());
    if (u.origin !== FREERO) return null;
    const m = BOARD.exec(u.pathname);
    if (!m) return null;
    return { boardId: m[1], item: u.searchParams.get('item') || u.searchParams.get('el') || u.searchParams.get('frame') || null };
  } catch (e) {
    return null;
  }
}

/** The board page Atlassian may frame: /atlassian/b/<id>, at the item, in the host's colour mode. */
export function boardSrc(target, colorMode) {
  const u = new URL('/atlassian/b/' + encodeURIComponent(target.boardId), FREERO);
  if (target.item) u.searchParams.set('item', target.item);
  if (colorMode === 'dark' || colorMode === 'light') u.searchParams.set('theme', colorMode);
  return u.toString();
}

export function el(tag, attrs, ...children) {
  const n = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs || {})) {
    if (k === 'onclick' || k === 'oninput') n[k] = v;
    else n.setAttribute(k, v);
  }
  for (const c of children) n.append(c);
  return n;
}
`;

  const boardJs = `// The macro and the issue panel: the board, framed from Freero (it follows Freero's sharing for
// each reader), or what to do when there is none yet.
import { requestJira, view } from '@forge/bridge';
import { boardFromLink, boardSrc, el, FREERO } from './shared.js';

const ISSUE_PROPERTY = 'freero-board';
const root = document.getElementById('root');

function show(target, colorMode) {
  root.replaceChildren(
    el('iframe', {
      src: boardSrc(target, colorMode),
      title: 'Freero board',
      allow: 'clipboard-read; clipboard-write; fullscreen',
      referrerpolicy: 'strict-origin-when-cross-origin',
    }),
  );
}

function message(text, extra) {
  root.replaceChildren(el('div', { class: 'note' }, el('p', {}, text), ...(extra ? [extra] : [])));
}

/** Jira: the board picked for the issue, else the first Freero link Freero's tracker sync put on it. */
async function issueBoard(key) {
  const prop = await requestJira('/rest/api/3/issue/' + encodeURIComponent(key) + '/properties/' + ISSUE_PROPERTY);
  if (prop.ok) {
    const v = (await prop.json()).value;
    const t = v && boardFromLink(v.link);
    if (t) return t;
  }
  const links = await requestJira('/rest/api/3/issue/' + encodeURIComponent(key) + '/remotelink');
  if (!links.ok) return null;
  for (const l of await links.json()) {
    const t = l && l.object && boardFromLink(l.object.url);
    if (t) return t;
  }
  return null;
}

function pickForIssue(key, colorMode) {
  const input = el('input', { type: 'url', placeholder: FREERO + '/board/…', 'aria-label': 'Freero board link' });
  const save = el('button', {
    type: 'button',
    onclick: async () => {
      const t = boardFromLink(input.value);
      if (!t) return message('That isn’t a link to a board on ' + new URL(FREERO).host + '.', form);
      const r = await requestJira('/rest/api/3/issue/' + encodeURIComponent(key) + '/properties/' + ISSUE_PROPERTY, {
        method: 'PUT',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ link: input.value.trim() }),
      });
      if (r.ok) show(t, colorMode);
      else message('Jira didn’t save the board (you need to be able to edit this issue).', form);
    },
  }, 'Show this board');
  const form = el('div', { class: 'pick' }, input, save);
  message('No Freero board is linked to this issue yet. Paste a board link:', form);
}

(async () => {
  const ctx = await view.getContext();
  await view.theme.enable().catch(() => undefined);
  const colorMode = (ctx.theme && ctx.theme.colorMode) || null;
  const ext = ctx.extension || {};
  if (ext.issue && ext.issue.key) {
    const t = await issueBoard(ext.issue.key).catch(() => null);
    return t ? show(t, colorMode) : pickForIssue(ext.issue.key, colorMode);
  }
  const t = boardFromLink(ext.config && ext.config.board) || boardFromLink(ext.autoConvertLink);
  if (t) return show(t, colorMode);
  message('Edit this macro and paste the link of a board on ' + new URL(FREERO).host + '.');
})();
`;

  const configJs = `// The macro's configuration: a board link of this Freero.
import { view } from '@forge/bridge';
import { boardFromLink, el, FREERO } from './shared.js';

(async () => {
  const ctx = await view.getContext();
  await view.theme.enable().catch(() => undefined);
  const current = (ctx.extension && ctx.extension.config && ctx.extension.config.board) || '';
  const input = el('input', { type: 'url', value: current, placeholder: FREERO + '/board/…', 'aria-label': 'Freero board link' });
  const status = el('p', { class: 'status', 'aria-live': 'polite' });
  const save = el('button', {
    type: 'button',
    onclick: () => {
      if (!boardFromLink(input.value)) {
        status.textContent = 'Paste the link of a board on ' + new URL(FREERO).host + ' (open the board in Freero and copy its address).';
        return;
      }
      view.submit({ config: { board: input.value.trim() } });
    },
  }, 'Save');
  document.getElementById('root').replaceChildren(
    el('label', { for: 'link' }, 'Freero board link'),
    input,
    el('p', { class: 'hint' }, 'Its owner must allow embedding (Share → Embed in Freero). Each reader sees it as Freero shares it with them.'),
    save,
    status,
  );
  input.id = 'link';
})();
`;

  const css = `html, body, #root { margin: 0; height: 100%; font: 14px/1.4 system-ui, sans-serif; color: var(--ds-text, #172b4d); background: transparent; }
iframe { display: block; width: 100%; height: 100%; min-height: 480px; border: 0; border-radius: 8px; }
.note, .pick, #root > label, #root > input, #root > p, #root > button { margin: 12px; }
input { box-sizing: border-box; width: calc(100% - 24px); padding: 8px; border: 1px solid var(--ds-border, #8590a2); border-radius: 4px; background: var(--ds-background-input, #fff); color: inherit; }
.pick input { width: 100%; margin-block-end: 8px; }
button { padding: 6px 12px; border: 0; border-radius: 4px; background: var(--ds-background-brand-bold, #0c66e4); color: var(--ds-text-inverse, #fff); cursor: pointer; }
.hint, .status { color: var(--ds-text-subtle, #44546f); }
`;
  const page = (title: string, script: string) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<link rel="stylesheet" href="./app.css">
</head>
<body>
<div id="root"></div>
<script src="./${script}"></script>
</body>
</html>
`;

  const exportJs = `// Page exports (PDF, Word): the board's link, with its picture when anyone with the link may view it
// (Freero's oEmbed answers only for such boards, so a private board's export names nothing of it).
import api from '@forge/api';

const FREERO = ${q(origin)};
const BOARD = /^\\/(?:board|embed\\/b|atlassian\\/b)\\/([A-Za-z0-9_-]{1,64})\\/?$/;

export async function exportBoard(payload) {
  const link = (payload && payload.extension && payload.extension.config && payload.extension.config.board) || (payload && payload.extension && payload.extension.autoConvertLink) || '';
  let url = null;
  try {
    const u = new URL(String(link).trim());
    const m = u.origin === FREERO ? BOARD.exec(u.pathname) : null;
    if (m) url = FREERO + '/board/' + encodeURIComponent(m[1]);
  } catch (e) {
    url = null;
  }
  if (!url) return { type: 'doc', version: 1, content: [{ type: 'paragraph', content: [{ type: 'text', text: 'Freero board' }] }] };
  let title = 'Freero board';
  let picture = null;
  try {
    const r = await api.fetch(FREERO + '/api/oembed?format=json&url=' + encodeURIComponent(url));
    if (r.ok) {
      const o = await r.json();
      if (o.title) title = String(o.title).slice(0, 200);
      if (o.thumbnail_url && String(o.thumbnail_url).startsWith(FREERO)) picture = o.thumbnail_url;
    }
  } catch (e) {
    /* the link alone */
  }
  const content = [];
  if (picture) content.push({ type: 'mediaSingle', attrs: { layout: 'center' }, content: [{ type: 'media', attrs: { type: 'external', url: picture } }] });
  content.push({ type: 'paragraph', content: [{ type: 'text', text: title, marks: [{ type: 'link', attrs: { href: url } }] }] });
  return { type: 'doc', version: 1, content };
}
`;

  const readme = `# Freero for Confluence and Jira (${host})

Generated by your Freero at ${origin}. See Freero's docs/integrations/atlassian.md for every step.

    npm install           # Atlassian's Forge packages and esbuild
    npm run build         # bundles static-src/ into static/
    forge deploy -e production
    forge install         # on your Confluence and Jira site

Don't edit the app id in manifest.yml: it is your Forge app's (ATLASSIAN_APP_ID on Freero).
`;

  return {
    'manifest.yml': manifest,
    'package.json': `${JSON.stringify(pkg, null, 2)}\n`,
    'README.md': readme,
    'src/index.js': exportJs,
    'static-src/shared.js': shared,
    'static-src/board.js': boardJs,
    'static-src/config.js': configJs,
    'static/board/index.html': page('Freero board', 'board.js'),
    'static/board/app.css': css,
    'static/config/index.html': page('Choose a Freero board', 'config.js'),
    'static/config/app.css': css,
    'static/icon.png': colorIcon(128),
    '.gitignore': 'node_modules/\nstatic/board/board.js\nstatic/config/config.js\n',
  };
}

/** The Forge app source as a zip, in a folder named after the app. */
export function forgeAppPackage(origin: string, appId: string): Uint8Array {
  const files = forgeAppFiles(origin, appId);
  return zipSync(Object.fromEntries(Object.entries(files).map(([p, v]) => [`freero-atlassian/${p}`, typeof v === 'string' ? Buffer.from(v) : v])));
}
