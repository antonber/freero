// Static files the pages reference. `asset()` returns the file's public URL under ASSETS_PREFIX
// with a content hash in its name (served immutable, cached for a year) and records it, so the
// build copies exactly what some page uses.
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ASSETS_PREFIX = '/_site';
export const SRC_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Files to emit: public file name → bytes. */
const emitted = new Map<string, Buffer>();

const hashOf = (bytes: Buffer) => createHash('sha256').update(bytes).digest('hex').slice(0, 10);

/** Registers generated bytes under `name` (e.g. 'og/claude.png') and returns its URL path. */
export function emitAsset(name: string, bytes: Buffer): string {
  const ext = path.extname(name);
  const file = `${name.slice(0, -ext.length)}-${hashOf(bytes)}${ext}`;
  emitted.set(file, bytes);
  return `${ASSETS_PREFIX}/${file}`;
}

/** A file from src/assets (or an absolute path) as a hashed public URL path. */
export function asset(rel: string): string {
  const abs = path.isAbsolute(rel) ? rel : path.join(SRC_DIR, 'assets', rel);
  return emitAsset(path.isAbsolute(rel) ? path.basename(rel) : rel, fs.readFileSync(abs));
}

export function emittedAssets(): ReadonlyMap<string, Buffer> {
  return emitted;
}

export function resetAssets(): void {
  emitted.clear();
}

/** Width and height of a WebP (lossy, lossless or extended), for <img width height>. */
export function webpSize(bytes: Buffer): { width: number; height: number } {
  if (bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WEBP') throw new Error('not a WebP file');
  const chunk = bytes.toString('ascii', 12, 16);
  if (chunk === 'VP8 ') return { width: bytes.readUInt16LE(26) & 0x3fff, height: bytes.readUInt16LE(28) & 0x3fff };
  if (chunk === 'VP8L') {
    const b = bytes.readUInt32LE(21);
    return { width: (b & 0x3fff) + 1, height: ((b >> 14) & 0x3fff) + 1 };
  }
  if (chunk === 'VP8X') return { width: bytes.readUIntLE(24, 3) + 1, height: bytes.readUIntLE(27, 3) + 1 };
  throw new Error(`unknown WebP chunk ${chunk}`);
}
